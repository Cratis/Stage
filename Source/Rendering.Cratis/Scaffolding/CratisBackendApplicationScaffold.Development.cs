    static string Readme(CratisBackendApplicationScaffoldRequest request) =>
        $$"""
        # {{request.ApplicationName}}

        Generated by Cratis Stage from a Screenplay model. The backend project is
        `{{request.ProjectName}}.csproj`; its root namespace is `{{request.RootNamespace}}`.

        ## Prerequisites

        - A .NET SDK supporting `{{request.Profile.TargetFramework}}`.
        - Node.js and Yarn for the Vite frontend.
        - Docker with Docker Compose for the development Chronicle and MongoDB services.

        ## Run locally

        From this directory, start the development services and backend:

        ```bash
        docker compose up -d
        dotnet run --project {{request.ProjectName}}.csproj
        ```

        In another terminal, install frontend dependencies and start Vite:

        ```bash
        yarn
        yarn dev
        ```

        Open the URL Vite prints. It proxies API requests to the backend.
        Use `yarn build` to build the frontend into `wwwroot` for the backend to serve.

        ## Run specifications

        ```bash
        dotnet test {{request.ProjectName}}.Specs -c Debug
        ```

        The separate specs project links the generated slice-local `when_*.cs` files.
        Their `#if DEBUG` wrappers keep them out of Release builds; the web project
        excludes specifications in every configuration.

        ## Customize

        Put adapters, partial `Program` hooks, dependency imports, and styles in
        `Customizations/`. Stage does not generate files there.

        Scaffold files belong to you after first run: preserve them by excluding the
        scaffold from subsequent plans. An application-scope plan includes it again;
        check your publisher's overwrite policy before applying one to an existing app.
        Edit `Directory.Packages.props` to bump centrally managed NuGet versions;
        keep Chronicle client, integration, testing, and development image versions aligned.
        Package references in `Customizations/Dependencies.props` can use a matching
        central `PackageVersion` or an explicit `VersionOverride`, not `Version`.
        Edit `package.json` for frontend dependencies.
        """;
