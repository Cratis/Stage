namespace Cratis.Stage.Rendering.Cratis.Scaffolding;

public sealed partial class CratisBackendApplicationScaffold
{
    internal static string EditorConfig() =>
        """
        root = true

        [*]
        charset = utf-8
        end_of_line = lf
        insert_final_newline = true
        indent_style = space

        [*.cs]
        indent_size = 4
        csharp_new_line_before_open_brace = all
        csharp_style_namespace_declarations = file_scoped:suggestion
        csharp_using_directive_placement = outside_namespace
        csharp_style_var_for_built_in_types = true:suggestion
        csharp_style_var_when_type_is_apparent = true:suggestion
        csharp_style_var_elsewhere = true:suggestion
        dotnet_sort_system_directives_first = true
        dotnet_separate_import_directive_groups = false

        [{**/when_*.cs,**/when_*/**/*.cs,**/for_*/**/*.cs,**/given/**/*.cs}]
        # Cratis specifications use BDD names, including should_ facts.
        dotnet_diagnostic.IDE1006.severity = none
        dotnet_diagnostic.CA1707.severity = none
        """;

    // A repository-root application builds its frontend with npm in CI, so its README names the same tool.
    static string FrontendTool(CratisBackendApplicationScaffoldRequest request) => request.RepositoryRoot ? "npm" : "Yarn";

    static string FrontendInstall(CratisBackendApplicationScaffoldRequest request) => request.RepositoryRoot ? "npm install" : "corepack enable\nyarn install";

    static string FrontendScript(CratisBackendApplicationScaffoldRequest request, string script) => request.RepositoryRoot ? $"npm run {script}" : $"yarn {script}";

    static string Readme(CratisBackendApplicationScaffoldRequest request) =>
        $$"""
        # {{request.ApplicationName}}

        Generated by Cratis Stage from a Screenplay model. The backend project is
        `{{request.ProjectName}}.csproj`; its root namespace is `{{request.RootNamespace}}`.

        ## Prerequisites

        - A .NET SDK supporting `{{request.Profile.TargetFramework}}`.
        - Node.js and {{FrontendTool(request)}} for the Vite frontend.
        - Docker with Docker Compose v2 supporting `--wait` for the development Chronicle and MongoDB services.

        ## Run locally

        From this directory, start the development services and backend:

        ```bash
        docker compose up -d --wait
        dotnet run --project {{request.ProjectName}}.csproj
        ```

        In another terminal, install frontend dependencies and start Vite:

        ```bash
        {{FrontendInstall(request)}}
        {{FrontendScript(request, "dev")}}
        ```

        Open the URL Vite prints. It proxies API requests to the backend.
        Use `{{FrontendScript(request, "build")}}` to build the frontend into `wwwroot` for the backend to serve.

        ## Run specifications

        ```bash
        dotnet test {{request.ProjectName}}.csproj
        ```

        Specifications live beside the slices they specify, in `when_*.cs` files and
        `when_*/`, `for_*/` and `given/` folders. They compile into the application in
        Debug, which is also when its test packages are referenced. A Release build
        removes them and needs no test packages.

        ## Customize

        Put adapters, partial `Program` hooks, dependency imports, and styles in
        `Customizations/`. Stage does not generate files there.

        Scaffold files belong to you after first run: preserve them by excluding the
        scaffold from subsequent plans. An application-scope plan includes it again;
        check your publisher's overwrite policy before applying one to an existing app.
        Edit `Directory.Packages.props` to bump centrally managed NuGet versions;
        keep Chronicle client, integration, testing, and development image versions aligned.
        Package references in `Customizations/Dependencies.props` can use a matching
        central `PackageVersion` or an explicit `VersionOverride`, not `Version`.
        Edit `package.json` for frontend dependencies.
        """;
}
